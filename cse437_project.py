# ===== DL Models + Training Helpers (PyTorch) =====

import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import TensorDataset, DataLoader


class TorchMLP(nn.Module):
    """Baseline MLP (your original)."""
    def __init__(self, input_dim: int, hidden_dims=(64, 32), dropout=0.3):
        super().__init__()
        layers = []
        prev = input_dim
        for h in hidden_dims:
            layers += [nn.Linear(prev, h), nn.ReLU(), nn.Dropout(dropout)]
            prev = h
        layers.append(nn.Linear(prev, 1))  # binary logit
        self.net = nn.Sequential(*layers)

    def forward(self, x):
        return self.net(x).squeeze(1)


class TorchMLP_BN(nn.Module):
    """
    MLP + BatchNorm: often more stable on tabular data than plain MLP.
    """
    def __init__(self, input_dim: int, hidden_dims=(256, 128, 64), dropout=0.3):
        super().__init__()
        layers = []
        prev = input_dim
        for h in hidden_dims:
            layers += [
                nn.Linear(prev, h),
                nn.BatchNorm1d(h),
                nn.ReLU(),
                nn.Dropout(dropout),
            ]
            prev = h
        layers.append(nn.Linear(prev, 1))  # binary logit
        self.net = nn.Sequential(*layers)

    def forward(self, x):
        return self.net(x).squeeze(1)


class ResidualBlock(nn.Module):
    """
    Residual block for tabular MLP.
    x -> Linear -> ReLU -> Dropout -> Linear -> add skip -> ReLU
    If dims mismatch, use projection on skip.
    """
    def __init__(self, in_dim: int, out_dim: int, dropout=0.3):
        super().__init__()
        self.fc1 = nn.Linear(in_dim, out_dim)
        self.fc2 = nn.Linear(out_dim, out_dim)
        self.act = nn.ReLU()
        self.drop = nn.Dropout(dropout)
        self.proj = nn.Linear(in_dim, out_dim) if in_dim != out_dim else None

    def forward(self, x):
        identity = x if self.proj is None else self.proj(x)
        out = self.fc1(x)
        out = self.act(out)
        out = self.drop(out)
        out = self.fc2(out)
        out = out + identity
        out = self.act(out)
        return out


class TorchResMLP(nn.Module):
    """Residual MLP for tabular data."""
    def __init__(self, input_dim: int, hidden_dims=(256, 256, 256), dropout=0.3):
        super().__init__()
        blocks = []
        prev = input_dim
        for h in hidden_dims:
            blocks.append(ResidualBlock(prev, h, dropout=dropout))
            prev = h
        self.blocks = nn.Sequential(*blocks)
        self.out = nn.Linear(prev, 1)

    def forward(self, x):
        x = self.blocks(x)
        return self.out(x).squeeze(1)


def train_mlp_minibatch(
    X_train: np.ndarray, y_train: np.ndarray,
    X_val: np.ndarray, y_val: np.ndarray,
    input_dim: int,

    # If model_builder is None, we'll build TorchMLP using hidden_dims/dropout below.
    model_builder=None,

    hidden_dims=(64, 32), dropout=0.3,
    lr=1e-3, weight_decay=1e-4,
    batch_size=32, max_epochs=200, patience=15,
    seed=42, device=None
):
    """
    Trains a PyTorch binary classifier with early stopping.
    - Uses BCEWithLogitsLoss with pos_weight to handle imbalance.
    - model_builder: function like lambda d: TorchMLP_BN(d, ...) OR lambda d: TorchResMLP(d, ...)
    """
    set_global_seed(seed)
    device = device or ("cuda" if torch.cuda.is_available() else "cpu")

    # Build model (default = TorchMLP)
    if model_builder is None:
        model = TorchMLP(input_dim=input_dim, hidden_dims=hidden_dims, dropout=dropout)
    else:
        model = model_builder(input_dim)

    model = model.to(device)

    pos_weight = get_pos_weight(y_train)
    criterion = nn.BCEWithLogitsLoss(
        pos_weight=torch.tensor(pos_weight, dtype=torch.float32, device=device)
    )
    optimizer = optim.Adam(model.parameters(), lr=lr, weight_decay=weight_decay)

    # Tensors
    X_tr_t = torch.tensor(X_train, dtype=torch.float32)
    y_tr_t = torch.tensor(y_train, dtype=torch.float32)
    X_va_t = torch.tensor(X_val, dtype=torch.float32).to(device)
    y_va_t = torch.tensor(y_val, dtype=torch.float32).to(device)

    ds = TensorDataset(X_tr_t, y_tr_t)
    loader = DataLoader(ds, batch_size=min(batch_size, len(ds)), shuffle=True)

    best_state, best_val, best_epoch, wait = None, float("inf"), -1, 0
    history = []

    for epoch in range(1, max_epochs + 1):
        model.train()
        total = 0.0

        for xb, yb in loader:
            xb, yb = xb.to(device), yb.to(device)

            optimizer.zero_grad()
            logits = model(xb)
            loss = criterion(logits, yb)
            loss.backward()
            optimizer.step()

            total += float(loss.item()) * len(xb)

        train_loss = total / len(ds)

        model.eval()
        with torch.no_grad():
            val_logits = model(X_va_t)
            val_loss = float(criterion(val_logits, y_va_t).item())

        history.append({"epoch": epoch, "train_loss": train_loss, "val_loss": val_loss})

        if val_loss < best_val - 1e-5:
            best_val = val_loss
            best_epoch = epoch
            best_state = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
            wait = 0
        else:
            wait += 1
            if wait >= patience:
                break

    if best_state is not None:
        model.load_state_dict(best_state)

    return model, pd.DataFrame(history), best_epoch, best_val


def predict_proba_torch(model: nn.Module, X: np.ndarray, device=None) -> np.ndarray:
    """Returns P(y=1) probabilities."""
    device = device or ("cuda" if torch.cuda.is_available() else "cpu")
    model.eval()
    with torch.no_grad():
        X_t = torch.tensor(X, dtype=torch.float32).to(device)
        logits = model(X_t)
        probs = torch.sigmoid(logits).detach().cpu().numpy()
        return probs

