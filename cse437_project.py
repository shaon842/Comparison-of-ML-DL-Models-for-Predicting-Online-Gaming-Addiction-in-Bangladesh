def evaluate_ml_setting(df: pd.DataFrame, features: list, setting_name: str, test_size=0.2, n_splits=5):
    split = split_train_test(df, features, test_size=test_size, seed=RANDOM_STATE)
    pos_weight = get_pos_weight(split.y_train)

    pre = build_preprocessor(df, features)
    models = get_ml_models(pos_weight)

    scoring = {
        "accuracy": "accuracy",
        "precision": "precision",
        "recall": "recall",
        "f1": "f1",
        "roc_auc": "roc_auc",
        "pr_auc": "average_precision",
    }
    cv = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=RANDOM_STATE)

    rows = []
    fitted = {}

    for name, model in models.items():
        # If model is already a Pipeline (GaussianNB case), keep it under 'model'
        pipe = Pipeline(steps=[("pre", pre), ("model", model)])

        cv_res = cross_validate(
            pipe, split.X_train, split.y_train,
            scoring=scoring, cv=cv, n_jobs=None, error_score="raise"
        )

        pipe.fit(split.X_train, split.y_train)
        fitted[name] = pipe

        y_score = predict_proba_or_score(pipe, split.X_test)
        y_pred = (y_score >= 0.5).astype(int)
        m = compute_metrics(split.y_test, y_score, y_pred)
        cm = confusion_matrix(split.y_test, y_pred)

        rows.append({
            "setting": setting_name,
            "model": name,
            "cv_accuracy_mean": float(np.mean(cv_res["test_accuracy"])),
            "cv_precision_mean": float(np.mean(cv_res["test_precision"])),
            "cv_recall_mean": float(np.mean(cv_res["test_recall"])),
            "cv_f1_mean": float(np.mean(cv_res["test_f1"])),
            "cv_roc_auc_mean": float(np.mean(cv_res["test_roc_auc"])),
            "cv_pr_auc_mean": float(np.mean(cv_res["test_pr_auc"])),
            **{f"test_{k}": v for k, v in m.items()},
            "confusion_matrix": cm.tolist(),
        })

    res = pd.DataFrame(rows).sort_values(by="test_f1", ascending=False).reset_index(drop=True)
    return res, fitted, split

