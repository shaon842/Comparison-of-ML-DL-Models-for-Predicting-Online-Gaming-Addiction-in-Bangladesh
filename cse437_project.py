"""# 5) Preprocessing Pipelines

We infer numeric vs categorical columns from the dataframe dtypes.

Pipeline:
- numeric: median impute → standardize
- categorical: most_frequent impute → one-hot encode

"""

def build_preprocessor(df: pd.DataFrame, features: list) -> ColumnTransformer:
    X = df[features].copy()
    num_cols = [c for c in features if pd.api.types.is_numeric_dtype(X[c])]
    cat_cols = [c for c in features if c not in num_cols]

    numeric_pipe = Pipeline(steps=[
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler()),
    ])

    categorical_pipe = Pipeline(steps=[
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("ohe", OneHotEncoder(handle_unknown="ignore")),
    ])

    pre = ColumnTransformer(
        transformers=[
            ("num", numeric_pipe, num_cols),
            ("cat", categorical_pipe, cat_cols),
        ],
        remainder="drop",
        sparse_threshold=0.3,
    )
    return pre

def get_pos_weight(y: np.ndarray) -> float:
    y = np.asarray(y).astype(int)
    n_pos = int((y == 1).sum())
    n_neg = int((y == 0).sum())
    return float(n_neg / max(n_pos, 1))

