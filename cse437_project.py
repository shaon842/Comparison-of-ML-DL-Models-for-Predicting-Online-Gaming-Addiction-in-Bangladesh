def clean_dataset_minimal(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()

    # Strip whitespace from column names
    df.columns = [str(c).strip() for c in df.columns]

    # Strip whitespace from string cells
    for c in df.columns:
        if df[c].dtype == "object":
            df[c] = df[c].astype(str).str.strip().replace({"nan": np.nan})

    # Robust binary mapping for Class
    def map_class(x):
        if pd.isna(x):
            return np.nan
        s = str(x).strip().lower()
        if s in {"y", "yes", "1", "true", "addicted", "positive"}:
            return 1
        if s in {"n", "no", "0", "false", "not addicted", "negative"}:
            return 0
        try:
            v = float(s)
            if v in [0.0, 1.0]:
                return int(v)
        except Exception:
            pass
        return np.nan

    df["Class"] = df["Class"].apply(map_class)

    before = len(df)
    df = df.dropna(subset=["Class"]).reset_index(drop=True)
    after = len(df)
    if after != before:
        print(f"Dropped {before-after} rows with missing/unknown Class.")

    df["Class"] = df["Class"].astype(int)

    if "Age" in df.columns:
        df["Age"] = pd.to_numeric(df["Age"], errors="coerce")

    return df

